import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {initialState,completeBattle} from '../dist/engine.mjs';
test('local server persists across restarts, protects existing data, rejects invalid requests',async t=>{
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),'fleet-test-')),port=14173,url=`http://127.0.0.1:${port}`;
  let child;
  const start=()=>new Promise((resolve,reject)=>{child=spawn(process.execPath,['server.mjs'],{cwd:new URL('..',import.meta.url),env:{...process.env,FLEET_PORT:String(port),FLEET_DATA_DIR:dir},stdio:['ignore','pipe','pipe']});child.stdout.once('data',resolve);child.once('error',reject);child.stderr.once('data',x=>reject(Error(String(x))));});
  const stop=()=>new Promise(resolve=>{child.once('exit',resolve);child.kill();});
  t.after(async()=>{if(child?.exitCode===null)await stop();fs.rmSync(dir,{recursive:true,force:true});});
  await start();assert.equal((await fetch(url)).status,200);
  const initial=await(await fetch(url+'/api/state')).json();assert.deepEqual(initial,initialState());
  const state=completeBattle(initial,'B1',23), put=s=>fetch(url+'/api/state',{method:'PUT',headers:{'Content-Type':'application/json'},body:JSON.stringify(s)});
  assert.equal((await put(state)).status,200);await stop();await start();assert.deepEqual(await(await fetch(url+'/api/state')).json(),state);
  assert.equal((await put({...state,version:99})).status,400);assert.deepEqual(await(await fetch(url+'/api/state')).json(),state);
  assert.equal((await fetch(url+'/api/state',{method:'PUT',headers:{Origin:'https://example.com','Content-Type':'application/json'},body:JSON.stringify(initial)})).status,403);
  assert.equal((await fetch(url+'/source/workbook.json')).status,404);assert.equal((await fetch(url+'/local-data/state.json')).status,404);
  assert.equal((await fetch(url+'/source/images/%2e%2e%2f%2e%2e%2fHANDOVER.md')).status,404);
  assert.match((await fetch(url+'/source/images/0/000')).headers.get('content-type'),/^image\//);
  const revised=completeBattle(state,'B2',12);await put(revised);assert.deepEqual(JSON.parse(fs.readFileSync(path.join(dir,'state.json.previous'))),state);
  // Legacy saves have no galaxy field and must remain G6-only.
  const legacy={...revised};delete legacy.galaxy;fs.writeFileSync(path.join(dir,'state.json'),JSON.stringify(legacy));
  assert.deepEqual(await(await fetch(url+'/api/state?galaxy=g6')).json(),legacy);
  const g7url=url+'/api/state?galaxy=g7',putG7=s=>fetch(g7url,{method:'PUT',headers:{'Content-Type':'application/json'},body:JSON.stringify(s)});
  assert.deepEqual(await(await fetch(g7url)).json(),initialState('g7'));
  const g7=completeBattle(initialState('g7'),'B2A',14);
  g7.conditions.B2A={support:true,hazard:false};
  g7.edits['0:A2:0']={multiplier:1.5,cost:14,support:false,hazard:false,special:false,enabled:true};
  assert.equal((await putG7(g7)).status,200);
  assert.equal((await putG7(legacy)).status,400);assert.equal((await put(g7)).status,400);
  assert.equal((await fetch(url+'/api/state?galaxy=unknown')).status,400);
  await stop();await start();
  assert.deepEqual(await(await fetch(g7url)).json(),g7);
  assert.deepEqual(await(await fetch(url+'/api/state')).json(),legacy);
  assert.deepEqual(JSON.parse(fs.readFileSync(path.join(dir,'state-g7.json'))),g7);
  assert.equal((await fetch(url+'/data-g7.json')).status,200);
  fs.writeFileSync(path.join(dir,'state.json'),'broken');assert.equal((await put(initial)).status,500);assert.equal(fs.readFileSync(path.join(dir,'state.json'),'utf8'),'broken');
});
